const near = (a, b, tol = 0.01) => Math.abs(a - b) <= tol * Math.max(1, Math.abs(b));
const T = [];
const test = (name, fn) => {
  try { const r = fn(); T.push({ name, ok: r === true, detail: r === true ? '' : String(r) }); }
  catch (e) { T.push({ name, ok: false, detail: e.stack.split('\n')[0] }); }
};

test('type names of other slicers map to our colors', () => {
  const m = { 'WALL-OUTER': 'outer', 'WALL-INNER': 'inner', SKIN: 'bottom', FILL: 'infill', SKIRT: 'skirt', SUPPORT: 'infill',
    'External perimeter': 'outer', Perimeter: 'inner', 'Solid infill': 'bottom', 'Internal infill': 'infill', 'Top solid infill': 'bottom', bottom: 'bottom', spiral: 'spiral' };
  const bad = Object.entries(m).filter(([k, v]) => normalizeType(k) !== v).map(([k]) => k);
  return bad.length ? 'wrong: ' + bad : true;
});
test('Cura: layers and types from the comments, G0 is travel, retract moves no clay', () => {
  const r = readGcode(cura);
  const ext = r.moves.filter(m => m.extrude);
  if (r.layers.length !== 2) return 'layers ' + r.layers.length;
  if (!r.hasTypes || !r.hasLayerMarks) return 'markers not seen';
  if (ext.length !== 6) return 'extruding moves ' + ext.length;
  if (r.moves.some(m => m.extrude && m.type === 'skirt' && m.layer !== 0)) return 'skirt layer';
  if (!ext.some(m => m.type === 'outer') || !ext.some(m => m.type === 'infill')) return 'types ' + [...new Set(ext.map(m => m.type))];
  if (r.moves.filter(m => !m.extrude).length < 2) return 'travel not seen';
  return true;
});
test('Cura: absolute E gives the clay of each move (E 1 per 10 mm)', () => {
  const r = readGcode(cura), m = r.moves.filter(x => x.extrude);
  if (!m.slice(0, 4).every(x => near(x.e, 1))) return m.slice(0, 4).map(x => x.e);
  return near(m[4].e, 1) ? true : 'after retract: ' + m[4].e;      // retract to 2.5 and back to 4, then E 5 is +1
});
test('PrusaSlicer: ;LAYER_CHANGE layers, relative E, type names', () => {
  const r = readGcode(prusa);
  if (r.layers.length !== 2) return 'layers ' + r.layers.length;
  const ext = r.moves.filter(m => m.extrude);
  if (ext.length !== 4 || ext[0].type !== 'outer' || ext[3].type !== 'bottom') return ext.map(m => m.type);
  return near(r.layers[1].z, 0.4) ? true : 'z ' + r.layers[1].z;
});
test('no layer comments: layers from the heights', () => {
  const r = readGcode(noMarks);
  if (r.hasLayerMarks) return 'marks?';
  if (r.layers.length !== 3) return 'layers ' + r.layers.length;
  return r.warnings.some(w => /No layer comments/.test(w)) ? true : 'no warning';
});
test('arcs G2 / G3 are cut into pieces and keep their length (quarter circles, r = 10)', () => {
  const r = readGcode(arcs), L = r.moves.reduce((s, m) => s + m.len, 0);
  const quarter = Math.PI * 10 / 2;
  return r.moves.length > 20 && near(L, 2 * quarter, 0.03) ? true : `len ${L.toFixed(2)}, expected ${(2 * quarter).toFixed(2)}, moves ${r.moves.length}`;
});
test('inches (G20) are converted to mm', () => {
  const r = readGcode(inches);
  return near(r.moves.at(-1).len, 25.4) ? true : 'len ' + r.moves.at(-1).len;
});
test('relative XYZ (G91)', () => {
  const r = readGcode(relXYZ);
  const e = r.moves.filter(m => m.extrude);
  return e.length === 2 && near(e[1].b[0], 10) && near(e[1].b[1], 5) ? true : JSON.stringify(e.map(m => m.b));
});
test('not G-code: no moves, no crash', () => readGcode(junk).moves.length === 0 ? true : 'moves found');
test('empty file', () => readGcode('').moves.length === 0 ? true : 'moves found');
test("this slicer's own G-code reads back with its types, layers, clay and path length (layered and spiral)", () => {
  const g = demoVaseGeometry(), pos = Array.from((g.index ? g.toNonIndexed() : g).getAttribute('position').array);
  for (const mode of ['layered', 'spiral']) {
    const { tp, gcode } = sliceModel(pos, { ...structuredClone(DEFAULTS), mode }, { top: 180 });
    const r = readGcode(gcode.text, { home: [0, 0, 400] });
    if (!r.hasTypes || !r.hasLayerMarks) return mode + ': no markers';
    if (r.layers.length !== tp.layers.length) return `${mode}: ${r.layers.length} layers, slicer ${tp.layers.length}`;
    if (!near(r.stats.volume, gcode.stats.volume, 0.02)) return `${mode}: clay ${r.stats.volume.toFixed(0)} vs ${gcode.stats.volume.toFixed(0)}`;
    if (!near(r.stats.extrudeLen, gcode.stats.extrudeLen, 0.02)) return `${mode}: path ${r.stats.extrudeLen.toFixed(0)} vs ${gcode.stats.extrudeLen.toFixed(0)}`;
  }
  return true;
});
test('a 60 000-move file reads in under 2 s', () => {
  let s = 'G90\nM83\nG1 X0 Y0 Z0.3 F3000\n';
  for (let i = 0; i < 60000; i++) s += `G1 X${(i % 100).toFixed(1)} Y${Math.floor(i / 100) % 100} Z${(0.3 + Math.floor(i / 10000) * 0.3).toFixed(2)} E0.05\n`;
  const t0 = performance.now(), r = readGcode(s), ms = performance.now() - t0;
  return r.moves.length > 50000 && ms < 2000 ? true : `${r.moves.length} moves in ${ms.toFixed(0)} ms`;
});

